export function IconSprite() {
  return (
    <svg width="0" height="0" style={{ position: 'absolute' }} aria-hidden="true" focusable="false">
      <defs>
        {Object.entries(ICONS).map(([id, shapes]) => (
          <symbol key={id} id={`i-${id}`} viewBox="0 0 24 24">
            {shapes.map((s, i) => {
              if ('p' in s) return <path key={i} d={s.p} />;
              if ('c' in s) return <circle key={i} cx={s.c[0]} cy={s.c[1]} r={s.c[2]} />;
              if ('l' in s) return <line key={i} x1={s.l[0]} y1={s.l[1]} x2={s.l[2]} y2={s.l[3]} />;
              const [x, y, w, h, r = 2] = s.r;
              return <rect key={i} x={x} y={y} width={w} height={h} rx={r} />;
            })}
          </symbol>
        ))}
      </defs>
    </svg>
  );
}

/**
 * An unknown name renders nothing rather than a broken reference — a missing
 * glyph should leave a gap, not an error in the console and an empty box on a
 * counter in Mwanza.
 */
export function Icon({ name, size = 18, ...rest }: { name: string; size?: number } & SVGProps<SVGSVGElement>) {
  if (!ICONS[name]) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      <use href={`#i-${name}`} />
    </svg>
  );
}

