// The paper stock sheet: a print-ready A4 page a bar prints at the start of a
// shift and fills in by hand at closing. Only the item name and its price are
// printed — every counting column is deliberately left blank so the person
// closing writes the real numbers in, then keys them into Bermi afterwards.

import { groupByCategory } from './calc';
import type { Business, Lang, Product } from './types';
import { countryByCode } from './countries';

const SLOGAN: Record<Lang, string> = {
  en: 'Your business. One system.',
  sw: 'Biashara yako. Mfumo mmoja.',
};

interface SheetLabels {
  title: string;
  counter: string;
  date: string;
  shift: string;
  item: string;
  opening: string;
  added: string;
  total: string;
  sold: string;
  remain: string;
  price: string;
  amount: string;
  categoryTotal: string;
  grandTotal: string;
  totalSold: string;
  expenses: string;
  cash: string;
  mobile: string;
  bank: string;
  debt: string;
  countedBy: string;
  checkedBy: string;
  footer: string;
}

